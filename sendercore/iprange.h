#pragma once
#include <QString>
#include <QStringList>

/// Разбирает диапазоны IPv4. Поддерживается (через запятую, пробел или с новой строки):
///   192.168.1.15              один адрес
///   192.168.1.10-192.168.1.50 диапазон
///   192.168.1.10-50           диапазон в последнем октете
///   192.168.1.0/24            подсеть (для /30 и шире без адресов сети и broadcast)
/// При ошибке возвращает пустой список и заполняет *error.
QStringList parseIpRanges(const QString &text, QString *error);
